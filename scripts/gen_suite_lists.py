#!/usr/bin/env python3
"""Generate the app set lists from lists/tetron.toml (WMINST-001).

The sets are defined once, in the "App sets" section of lists/tetron.toml:
[[package]] entries, [[app]] entries with `set` (package names from their
merged pkg) and [[script]] entries. This writes:

1. assets/suite-apps.txt, the suite installer's list: one line per package

       size:group:check:apt:dnf:pacman:brew

   and one per app no distribution packages

       size:script:name

   and one per member with a release to fall back on ([[release]])

       size:release:check:repo:amd64-asset:arm64-asset

   size is essentials, recommended or extras (a size installs its own lines
   and the smaller sizes' lines; the desktop set is part of essentials); group
   is apps, gui (only with a desktop session) or services (the separate,
   default-no question). An empty name means "not on that system". Entries
   without a check are left out: they are in the deb only.
2. the `recommends` array of each size deb's packaging/<set>.toml
   (tetron-wm-desktop, -essentials, -recommended, -extras); services stay
   hand-written Suggests there and must be listed.

    python3 scripts/gen_suite_lists.py           write both
    python3 scripts/gen_suite_lists.py --check   exit 1 if either is out of date
"""
import re
import sys
import tomllib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import merge_catalog  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
PKG = ROOT / "packaging"
OUT = ROOT / "assets" / "suite-apps.txt"
SETS = ("desktop", "essentials", "recommended", "extras")
# The suite size a set belongs to.
SIZE = {"desktop": "essentials", "essentials": "essentials", "recommended": "recommended", "extras": "extras"}
MANAGERS = ("apt", "dnf", "pacman", "brew")
GROUPS = ("apps", "gui", "services")
PACKAGE_KEYS = {"name", "set", "check", "group", "deb", *MANAGERS}
HEADER = ("# Generated by scripts/gen_suite_lists.py from lists/tetron.toml. Do not edit.\n"
          "# size:group:check:apt:dnf:pacman:brew, size:script:name, or size:release:check:repo:amd64:arm64\n")
RECOMMENDS = re.compile(r"^recommends = \[[^\n]*\]\n|^recommends = \[\n.*?^\]\n", re.S | re.M)


class GenError(Exception):
    pass


def debian_name(rel: str) -> str:
    """The first alternative's package name: "7zip | p7zip-full" -> "7zip"."""
    return rel.split("|")[0].split("(")[0].strip()


def members(ours: dict, apps: list) -> list[dict]:
    """Every set member in file order, packages then apps, as
    {name, set, group, check, deb, apt, dnf, pacman, brew} ("" = none)."""
    out = []
    for p in ours.get("package", []):
        n = p.get("name", "?")
        if set(p) - PACKAGE_KEYS:
            raise GenError(f"package {n}: unknown fields {sorted(set(p) - PACKAGE_KEYS)}")
        if p.get("set") not in SETS:
            raise GenError(f"package {n}: set must be one of {list(SETS)}")
        if p.get("group", "apps") not in GROUPS:
            raise GenError(f"package {n}: group must be one of {list(GROUPS)}")
        names = {m: p.get(m, n) for m in MANAGERS}
        deb = p.get("deb", names["apt"])
        if deb and debian_name(deb) != names["apt"]:
            raise GenError(f"package {n}: deb {deb!r} does not start with its apt name {names['apt']!r}")
        out.append(dict(names, name=n, set=p["set"], group=p.get("group", "apps"), check=p.get("check", ""), deb=deb))
    for a in sorted(apps, key=lambda a: a["name"].lower()):
        if "set" in a:
            pk = a.get("pkg", {})
            names = {m: pk.get(m, "") for m in MANAGERS}
            out.append(dict(names, name=a["name"], set=a["set"], group="apps", check=a["bin"], deb=names["apt"]))
    seen = set()
    for m in out:
        if m["name"].lower() in seen:
            raise GenError(f"{m['name']} is listed twice")
        seen.add(m["name"].lower())
    return out


def generate(ours: dict, apps: list, debs: dict) -> tuple[str, dict]:
    """(suite-apps.txt text, {set: deb toml text with its recommends written})."""
    ms = members(ours, apps)
    lines = []
    for m in ms:
        if not m["check"]:
            if not m["deb"]:
                raise GenError(f"{m['name']}: no check and no deb name, so nothing installs it")
            continue
        fields = [SIZE[m["set"]], m["group"], m["check"]] + [m[k] for k in MANAGERS]
        if any(":" in f for f in fields):
            raise GenError(f"{m['name']}: ':' is the field separator")
        lines.append(":".join(fields))
    for s in ours.get("script", []):
        if s.get("set") not in SIZE or not s.get("how") or not s.get("name"):
            raise GenError(f"script {s.get('name', '?')}: needs name, set ({list(SIZE)}) and how")
        lines.append(f"{SIZE[s['set']]}:script:{s['name']}")
    by_name = {m["name"].lower(): m for m in ms}
    for r in ours.get("release", []):
        m = by_name.get(str(r.get("name", "")).lower())
        if not m or not m["check"]:
            raise GenError(f"release {r.get('name', '?')}: not a set member with a check")
        if set(r) - {"name", "repo", "amd64", "arm64"} or not r.get("repo") or not (r.get("amd64") or r.get("arm64")):
            raise GenError(f"release {r['name']}: needs repo and amd64 or arm64, nothing else")
        fields = [SIZE[m["set"]], "release", m["check"], r["repo"], r.get("amd64", ""), r.get("arm64", "")]
        if any(":" in f for f in fields):
            raise GenError(f"release {r['name']}: ':' is the field separator")
        lines.append(":".join(fields))
    out = {}
    for name, text in debs.items():
        d = tomllib.loads(text)
        suggests = {debian_name(r) for r in d.get("suggests", [])}
        rec = [m["deb"] for m in ms if m["set"] == name and m["group"] != "services" and m["deb"]]
        for m in ms:
            if m["set"] == name and m["group"] == "services" and m["apt"] and m["apt"] not in suggests:
                raise GenError(f"packaging/{name}.toml: service {m['apt']} must be in suggests")
        if not RECOMMENDS.search(text):
            raise GenError(f"packaging/{name}.toml: no recommends array")
        body = "".join(f'  "{r}",\n' for r in rec)
        new = f"recommends = [\n{body}]\n" if rec else "recommends = []\n"
        out[name] = RECOMMENDS.sub(lambda _: new, text, count=1)
    return HEADER + "\n".join(lines) + "\n", out


def main(argv: list[str]) -> int:
    ours = tomllib.loads((ROOT / "lists" / "tetron.toml").read_text(encoding="utf-8"))
    debs = {s: (PKG / f"{s}.toml").read_text() for s in SETS}
    try:
        text, new_debs = generate(ours, merge_catalog.merged_apps(), debs)
    except GenError as e:
        print(f"gen_suite_lists: {e}", file=sys.stderr)
        return 1
    stale = (["assets/suite-apps.txt"] if not OUT.exists() or OUT.read_text() != text else []) + \
        [f"packaging/{s}.toml" for s in SETS if debs[s] != new_debs[s]]
    if "--check" in argv:
        if stale:
            print(f"gen_suite_lists: out of date: {', '.join(stale)}; run python3 scripts/gen_suite_lists.py",
                  file=sys.stderr)
        return 1 if stale else 0
    OUT.write_text(text)
    for s in SETS:
        (PKG / f"{s}.toml").write_text(new_debs[s])
    print(f"wrote assets/suite-apps.txt ({text.count(chr(10)) - 2} entries) and packaging/{{{','.join(SETS)}}}.toml")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
